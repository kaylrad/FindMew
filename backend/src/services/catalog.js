export function settlePet(pet, now = Date.now()) {
  const hours = Math.max(0, (now - Date.parse(pet.updated_at)) / 3600000),
    result = { ...pet, updated_at: new Date(now).toISOString() };
  for (const [field, rate] of [
    ['energy', 2],
    ['clean', 1],
    ['happiness', 1.5],
  ]) {
    const elapsed = (pet[field + '_remainder'] || 0) + hours * rate,
      whole = Math.floor(elapsed);
    result[field] = Math.max(0, pet[field] - whole);
    result[field + '_remainder'] = elapsed - whole;
  }
  return result;
}
export function effectivePet(pet, now = Date.now()) {
  const { energy_remainder, clean_remainder, happiness_remainder, ...result } = settlePet(pet, now);
  return { ...result, updated_at: pet.updated_at };
}
